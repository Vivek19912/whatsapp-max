/**
 * Hydrated member row for the Settings → Members tab. Combines
 * the profile and its account_role for a single member of the
 * caller's account. Sensitive fields (email) are populated only
 * when the caller has admin+ — agents and viewers see name +
 * avatar + role only.
 */
export interface AccountMember {
  user_id: string;
  full_name: string;
  email: string | null;
  avatar_url: string | null;
  role: AccountRole;
  joined_at: string;
  /** Effective WhatsApp recording source ('none' when unset). */
  whatsapp_recording_source: string;
  /** Effective phone recording source ('none' when unset). Legacy slot value. */
  phone_recording_source: string;
  /** Owner-configured phone number, normalized digits (null = none). */
  phone_recording_number: string | null;
  /**
   * Inbox grant flags. Present ONLY for the owner caller (merged
   * server-side from agent_inbox_permissions); absent for everyone
   * else. True = the agent holds that grant right now.
   */
  can_manage_assignments?: boolean;
  can_view_all?: boolean;
}

